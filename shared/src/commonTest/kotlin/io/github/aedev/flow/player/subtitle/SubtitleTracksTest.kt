package io.github.aedev.flow.player.subtitle

import io.github.aedev.flow.testing.assertThat
import io.github.aedev.flow.player.media.MediaLoader
import io.github.aedev.flow.player.state.SubtitleOrigin
import io.github.aedev.flow.player.stream.CaptionFormat
import io.github.aedev.flow.player.stream.ResolvedCaption
import kotlin.test.Test

class SubtitleTracksTest {
    private fun online(
        language: String,
        signature: String = "a",
    ) = ResolvedCaption(
        language,
        isAutoGenerated = false,
        url = "https://yt/timedtext?lang=$language&sig=$signature",
        format = CaptionFormat.SRV3,
    )

    private val englishOn = SubtitleAutoPolicy(enabled = true, languageTag = "en")

    @Test
    fun automaticCaptionsFollowThePolicyUntilSomeonePicks() {
        val tracks = SubtitleTracks()
        tracks.load("v1", listOf(online("de"), online("en")), acceptsEmbedded = false)

        assertThat(tracks.selected).isNull()
        assertThat(tracks.setPolicy(englishOn)).isTrue()
        assertThat(tracks.selected?.language).isEqualTo("en")
    }

    @Test
    fun aPickSurvivesTheSameVideoComingBackUnderNewSignedUrls() {
        val tracks = SubtitleTracks()
        tracks.setPolicy(englishOn)
        tracks.load("v1", listOf(online("de"), online("en")), acceptsEmbedded = false)
        tracks.select(tracks.options.first { it.language == "de" }.url)

        tracks.load("v1", emptyList(), acceptsEmbedded = false)
        tracks.load("v1", listOf(online("de", signature = "b"), online("en", signature = "b")), acceptsEmbedded = false)

        assertThat(tracks.selected?.url).isEqualTo(online("de", signature = "b").url)
        assertThat(tracks.setPolicy(SubtitleAutoPolicy.OFF)).isFalse()
    }

    @Test
    fun turningCaptionsOffSticksForTheVideoAndANewVideoStartsFresh() {
        val tracks = SubtitleTracks()
        tracks.setPolicy(englishOn)
        tracks.load("v1", listOf(online("en")), acceptsEmbedded = false)
        tracks.select(null)
        tracks.load("v1", listOf(online("en", signature = "b")), acceptsEmbedded = false)

        assertThat(tracks.selected).isNull()

        tracks.load("v2", listOf(online("en")), acceptsEmbedded = false)
        assertThat(tracks.selected?.language).isEqualTo("en")
    }

    @Test
    fun tracksInsideADeviceFileJoinTheListAndAForcedOneShowsWithCaptionsOff() {
        val tracks = SubtitleTracks()
        tracks.load("local_1", emptyList(), acceptsEmbedded = true)

        val changed = tracks.onTracksChanged(textTracks(format("3", "en", forced = false), format("4", "ja", forced = true)))

        assertThat(changed).isTrue()
        assertThat(tracks.options.map { it.url }).containsExactly("embedded:3", "embedded:4").inOrder()
        assertThat(tracks.options.all { it.origin == SubtitleOrigin.EMBEDDED }).isTrue()
        assertThat(tracks.selected?.url).isEqualTo("embedded:4")
        assertThat(tracks.onTracksChanged(textTracks(format("3", "en", forced = false), format("4", "ja", forced = true)))).isFalse()
    }

    @Test
    fun flowSOwnCaptionTracksAndOnlineVideosNeverListEmbeddedTracks() {
        val tracks = SubtitleTracks()
        tracks.load("local_1", emptyList(), acceptsEmbedded = true)
        assertThat(tracks.onTracksChanged(textTracks(format(MediaLoader.subtitleTrackId(0), "en", forced = false)))).isFalse()
        // A merging source prefixes each format id with its source's position.
        assertThat(tracks.onTracksChanged(textTracks(format("1:${MediaLoader.subtitleTrackId(3)}", "en", forced = false)))).isFalse()

        tracks.load("v1", emptyList(), acceptsEmbedded = false)
        assertThat(tracks.onTracksChanged(textTracks(format("3", "en", forced = false)))).isFalse()
        assertThat(tracks.options).isEmpty()
    }

    @Test
    fun captionIndexesAreReadBackFromPrefixedFormatIds() {
        assertThat(MediaLoader.subtitleTrackIndex("2:flow-subtitle-12")).isEqualTo(12)
        assertThat(MediaLoader.subtitleTrackIndex(MediaLoader.subtitleTrackId(0))).isEqualTo(0)
        assertThat(MediaLoader.subtitleTrackIndex("3")).isNull()
        assertThat(MediaLoader.subtitleTrackIndex(null)).isNull()
    }

    // Media3's text Format and Tracks become the engine's report of the file's text tracks.
    private fun format(
        id: String,
        language: String,
        forced: Boolean,
    ): EmbeddedTextTrack = EmbeddedTextTrack(id = id, language = language, isForced = forced)

    private fun textTracks(vararg formats: EmbeddedTextTrack): List<EmbeddedTextTrack> = formats.toList()
}
