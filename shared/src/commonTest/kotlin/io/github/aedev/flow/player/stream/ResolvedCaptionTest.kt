package io.github.aedev.flow.player.stream

import io.github.aedev.flow.testing.assertEquals
import io.github.aedev.flow.testing.assertFalse
import io.github.aedev.flow.testing.assertNull
import io.github.aedev.flow.testing.assertTrue
import kotlin.test.Test

class ResolvedCaptionTest {
    @Test
    fun aTranslatedCaptionIsToldApartByItsTlangParameter() {
        val base = "https://www.youtube.com/api/timedtext?v=x&lang=en&fmt=vtt"

        assertFalse(ResolvedCaption("en", isAutoGenerated = false, url = base, format = CaptionFormat.VTT).isTranslated)
        assertTrue(ResolvedCaption("es", isAutoGenerated = true, url = "$base&tlang=es", format = CaptionFormat.VTT).isTranslated)
    }

    @Test
    fun subtitleFileExtensionsMapToTheFormatsMedia3Reads() {
        assertEquals(CaptionFormat.SRT, CaptionFormat.ofExtension("SRT"))
        assertEquals(CaptionFormat.SSA, CaptionFormat.ofExtension("ass"))
        assertEquals(CaptionFormat.TTML, CaptionFormat.ofExtension("dfxp"))
        assertEquals("text/vtt", CaptionFormat.ofExtension("vtt")?.mimeType)
        assertNull(CaptionFormat.ofExtension("sub"))
    }
}
