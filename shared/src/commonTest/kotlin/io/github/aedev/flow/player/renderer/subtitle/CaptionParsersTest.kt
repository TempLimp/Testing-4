package io.github.aedev.flow.player.renderer.subtitle

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.text.font.FontStyle
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.text.style.TextAlign
import androidx.compose.ui.text.style.TextDecoration
import io.github.aedev.flow.player.subtitle.SubtitleDelay
import io.github.aedev.flow.player.subtitle.toRollingCaptionText
import io.github.aedev.flow.testing.assertEquals
import io.github.aedev.flow.testing.assertThat
import kotlin.test.Test

/** The port's caption pipeline, which stands in for Media3's text renderer (WebVTT and srv3 by Media3's rules). */
class CaptionParsersTest {
    private fun vtt(body: String): Subtitle = WebvttParser().parseToLegacySubtitle(("WEBVTT\nKind: captions\nLanguage: en\n\n" + body).encodeToByteArray())

    private fun Subtitle.textAt(seconds: Double): List<String> = getCues((seconds * 1_000_000).toLong()).map { it.text.toString() }

    @Test
    fun aVttCueShowsFromItsStartUntilItsEnd() {
        val subtitle = vtt("00:00:01.000 --> 00:00:03.500\nHello\nworld\n")

        assertThat(subtitle.textAt(0.5)).isEmpty()
        assertThat(subtitle.textAt(1.0)).containsExactly("Hello\nworld")
        assertThat(subtitle.textAt(3.499)).containsExactly("Hello\nworld")
        assertThat(subtitle.textAt(3.5)).isEmpty()
        assertEquals(1_000_000L, subtitle.getEventTime(0))
        assertEquals(1, subtitle.getNextEventTimeIndex(2_000_000L))
    }

    @Test
    fun hourlessAndHourTimestampsBothParse() {
        assertEquals(61_500_000L, WebvttParser.parseTimestampUs("01:01.500"))
        assertEquals(3_661_500_000L, WebvttParser.parseTimestampUs("01:01:01.500"))
        assertEquals(null, WebvttParser.parseTimestampUs("01:01"))
    }

    @Test
    fun youtubeAutoGeneratedCuesDropInlineTimestampsAndKeepTheirLines() {
        val subtitle =
            vtt(
                "00:00:00.160 --> 00:00:02.149 align:start position:0%\n \n" +
                    "we're<00:00:00.480><c> going</c><00:00:00.640><c> to</c>\n",
            )
        val cue = subtitle.getCues(1_000_000L).single()

        // Media3 trims each text line, so the blank first line stays as an empty one.
        assertEquals("\nwe're going to", cue.text.toString())
        assertEquals(TextAlign.Start, cue.textAlignment)
        assertEquals(0f, cue.position)
        assertEquals(Cue.ANCHOR_TYPE_START, cue.positionAnchor)
        assertEquals(1f, cue.size)
        assertEquals("we're going to", listOf(cue).toRollingCaptionText())
    }

    @Test
    fun cueSettingsFollowMedia3() {
        val cue = vtt("00:00:01.000 --> 00:00:02.000 line:10% position:30%,line-right align:end size:50%\nX\n").getCues(1_000_000L).single()

        assertEquals(0.1f, cue.line)
        assertEquals(Cue.LINE_TYPE_FRACTION, cue.lineType)
        assertEquals(Cue.ANCHOR_TYPE_START, cue.lineAnchor)
        assertEquals(0.3f, cue.position)
        assertEquals(Cue.ANCHOR_TYPE_END, cue.positionAnchor)
        assertEquals(TextAlign.End, cue.textAlignment)
        // An end-anchored cue at 30% can be at most 30% wide.
        assertEquals(0.3f, cue.size)
    }

    @Test
    fun aCenteredCueDefaultsToTheMiddle() {
        val cue = vtt("00:00:01.000 --> 00:00:02.000\nX\n").getCues(1_000_000L).single()

        assertEquals(TextAlign.Center, cue.textAlignment)
        assertEquals(0.5f, cue.position)
        assertEquals(Cue.ANCHOR_TYPE_MIDDLE, cue.positionAnchor)
        assertEquals(-1f, cue.line)
        assertEquals(Cue.LINE_TYPE_NUMBER, cue.lineType)
    }

    @Test
    fun overlappingCuesWithoutALineStackUpFromTheBottomInStartOrder() {
        val subtitle = vtt("00:00:01.000 --> 00:00:04.000\nfirst\n\n00:00:02.000 --> 00:00:03.000\nsecond\n")
        val cues = subtitle.getCues(2_500_000L)

        assertThat(cues.map { it.text.toString() to it.line }).containsExactly("first" to -1f, "second" to -2f)
        assertThat(subtitle.textAt(3.5)).containsExactly("first")
    }

    @Test
    fun tagsBecomeStylesAndEntitiesTheirCharacters() {
        val cue = vtt("00:00:01.000 --> 00:00:02.000\n<b>bold</b> <i>it</i> <u>un</u> &lt;&amp;&gt;&nbsp;x &foo; y\n").getCues(1_000_000L).single()
        val text = cue.text!!

        assertEquals("bold it un <&> x  y", text.text)
        assertThat(text.spanStyles.map { Triple(it.item.fontWeight, it.start, it.end) }).contains(Triple(FontWeight.Bold, 0, 4))
        assertThat(text.spanStyles.map { Triple(it.item.fontStyle, it.start, it.end) }).contains(Triple(FontStyle.Italic, 5, 7))
        assertThat(text.spanStyles.map { Triple(it.item.textDecoration, it.start, it.end) }).contains(Triple(TextDecoration.Underline, 8, 10))
    }

    @Test
    fun rubyTextIsLeftOutAndItsBaseKept() {
        val cue = vtt("00:00:01.000 --> 00:00:02.000\n<ruby>漢<rt>かん</rt></ruby>字\n").getCues(1_000_000L).single()

        assertEquals("漢字", cue.text.toString())
    }

    @Test
    fun styleBlocksColourTheirClassesAndTheWholeCueComesLast() {
        val subtitle =
            vtt(
                "STYLE\n::cue(c.colorE5E5E5) { color: rgb(229,229,229); }\n::cue { background-color: rgba(0,0,0,0.5); }\n\n" +
                    "00:00:01.000 --> 00:00:02.000\n<c.colorE5E5E5>grey</c> plain\n",
            )
        val text = subtitle.getCues(1_000_000L).single().text!!

        val grey = text.spanStyles.single { it.item.color != Color.Unspecified }
        assertEquals(Color(229, 229, 229), grey.item.color)
        assertEquals(0 to 4, grey.start to grey.end)
        val background = text.spanStyles.last()
        assertEquals(Color(0, 0, 0, 127), background.item.background)
        assertEquals(0 to text.length, background.start to background.end)
    }

    @Test
    fun notesAndCueIdsAreSkipped() {
        val subtitle = vtt("NOTE a comment\nspanning lines\n\nintro\n00:00:01.000 --> 00:00:02.000\nHi\n")

        assertThat(subtitle.textAt(1.5)).containsExactly("Hi")
    }

    @Test
    fun aFileWithoutTheHeaderGivesNoCues() {
        val subtitle = WebvttParser().parseToLegacySubtitle("00:00:01.000 --> 00:00:02.000\nHi\n".encodeToByteArray())

        assertEquals(0, subtitle.getEventTimeCount())
    }

    @Test
    fun srv3ParagraphsKeepTheirPensAndWindows() {
        val xml =
            """
            <timedtext format="3"><head>
              <pen id="1" b="1" fc="#FFFF00" fo="127"/>
              <ws id="1" ju="0"/><wp id="1" ap="0" ah="10" av="20"/>
            </head><body>
              <p t="1000" d="2000" p="1" ws="1" wp="1">  Hi there  </p>
              <p t="4000" d="1000">plain</p>
            </body></timedtext>
            """.trimIndent()
        val subtitle = Srv3SubtitleParser().parseToLegacySubtitle(xml.encodeToByteArray())

        val styled = subtitle.getCues(1_500_000L).single()
        assertEquals("Hi there", styled.text.toString())
        assertEquals(FontWeight.Bold, styled.text!!.spanStyles.first().item.fontWeight)
        assertEquals(Color(0x7FFFFF00), styled.text!!.spanStyles.single { it.item.color != Color.Unspecified }.item.color)
        assertEquals(TextAlign.Start, styled.textAlignment)
        assertEquals(0.2f, styled.line)
        assertEquals(Cue.LINE_TYPE_FRACTION, styled.lineType)
        assertEquals(Cue.ANCHOR_TYPE_START, styled.lineAnchor)
        assertEquals(0.1f, styled.position)
        assertEquals(Cue.ANCHOR_TYPE_START, styled.positionAnchor)

        val plain = subtitle.getCues(4_500_000L).single()
        assertEquals(Cue.DIMEN_UNSET, plain.line)
        assertEquals(TextAlign.Center, plain.textAlignment)
        assertThat(subtitle.getCues(3_500_000L)).isEmpty()
    }

    @Test
    fun overlappingSrv3ParagraphsAreTruncatedAsMedia3Does() {
        val xml = """<timedtext format="3"><body><p t="0" d="3000">one</p><p t="1000" d="1000">two</p></body></timedtext>"""
        val subtitle = Srv3SubtitleParser().parseToLegacySubtitle(xml.encodeToByteArray())

        // The first keeps its start, the second cuts it short, and the first's tail is lost.
        assertThat(subtitle.textAt(0.5)).containsExactly("one")
        assertThat(subtitle.textAt(1.5)).containsExactly("two")
        assertThat(subtitle.textAt(2.5)).isEmpty()
    }

    @Test
    fun theDecoderShiftsCaptionsByTheCurrentOffset() {
        val delay = SubtitleDelay()
        val subtitle = DelayedSubtitleDecoder(WebvttParser(), delay).decode("WEBVTT\n\n00:00:01.000 --> 00:00:02.000\nHi\n".encodeToByteArray())

        assertThat(subtitle.textAt(1.5)).containsExactly("Hi")
        delay.offsetUs = 1_000_000L
        assertThat(subtitle.textAt(1.5)).isEmpty()
        assertThat(subtitle.textAt(2.5)).containsExactly("Hi")
    }

    @Test
    fun androidColorNamesAndHexParseAsAndroidDoes() {
        assertEquals(0xFFFF0000.toInt(), parseAndroidColor("#FF0000"))
        assertEquals(0x80FF0000.toInt(), parseAndroidColor("#80FF0000"))
        assertEquals(0xFF008080.toInt(), parseAndroidColor("teal"))
        assertEquals(null, parseAndroidColor("#F00"))
    }
}
