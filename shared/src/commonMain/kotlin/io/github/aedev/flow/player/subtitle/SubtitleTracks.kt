package io.github.aedev.flow.player.subtitle

import io.github.aedev.flow.player.media.MediaLoader
import io.github.aedev.flow.player.state.SubtitleOption
import io.github.aedev.flow.player.state.SubtitleOrigin
import io.github.aedev.flow.player.stream.ResolvedCaption
import io.github.aedev.flow.player.stream.StreamProcessor

/**
 * A text track inside a device file, with the fields of Media3's text `Format` that upstream reads: its id, language,
 * label, and whether it is forced or machine-written. An engine that finds such tracks reports them (device files, S19).
 */
data class EmbeddedTextTrack(
    val id: String?,
    val language: String?,
    val label: String? = null,
    val isForced: Boolean = false,
    val isMachineText: Boolean = false,
)

/**
 * The subtitle options of the video that plays and which one shows: the captions Flow found plus, for a device
 * file, the text tracks inside it. Upstream applies the choice to Media3's track selector; on iOS the manager loads
 * the caption [selectedCaption] names and hands it to the player, since neither engine renders text.
 */
internal class SubtitleTracks {
    private var videoId: String? = null
    private var acceptsEmbedded = false
    private var embedded: List<SubtitleOption> = emptyList()
    private var pick: Pick? = null

    var captions: List<ResolvedCaption> = emptyList()
        private set

    var policy: SubtitleAutoPolicy = SubtitleAutoPolicy.OFF
        private set

    val options: List<SubtitleOption>
        get() = StreamProcessor.toSubtitleOptions(captions) + embedded

    val selected: SubtitleOption?
        get() =
            when (val current = pick) {
                null -> SubtitleChoice.automatic(options, policy)
                Pick.Off -> null
                is Pick.Track -> options.firstOrNull { identity(it) == current.identity }
            }

    /** The caption file the selection shows; null for none, or for a track inside the file (its engine shows it). */
    fun selectedCaption(): ResolvedCaption? {
        val option = selected ?: return null
        if (option.origin == SubtitleOrigin.EMBEDDED) return null
        return captions.firstOrNull { it.url == option.url }
    }

    fun load(
        videoId: String?,
        captions: List<ResolvedCaption>,
        acceptsEmbedded: Boolean,
    ) {
        if (videoId != this.videoId) {
            pick = null
            embedded = emptyList()
        }
        this.videoId = videoId
        this.captions = captions
        this.acceptsEmbedded = acceptsEmbedded
        if (!acceptsEmbedded) embedded = emptyList()
    }

    fun select(url: String?) {
        pick =
            if (url == null) {
                Pick.Off
            } else {
                options.firstOrNull { it.url == url }?.let { Pick.Track(identity(it)) } ?: return
            }
    }

    fun setPolicy(policy: SubtitleAutoPolicy): Boolean {
        if (policy == this.policy) return false
        this.policy = policy
        return pick == null
    }

    /** The text tracks the playing file holds; true when the options changed. */
    fun onTracksChanged(tracks: List<EmbeddedTextTrack>): Boolean {
        if (!acceptsEmbedded) return false
        val found =
            tracks
                .withIndex()
                .filter { MediaLoader.subtitleTrackIndex(it.value.id) == null }
                .distinctBy { keyOf(it.value, it.index) }
                .map { (index, track) -> track.toOption(keyOf(track, index)) }
        if (found == embedded) return false
        embedded = found
        return true
    }

    private fun identity(option: SubtitleOption): String =
        when (option.origin) {
            SubtitleOrigin.ONLINE -> "online|${option.language}|${option.isAutoGenerated}|${option.isTranslated}"
            else -> option.url
        }

    private fun EmbeddedTextTrack.toOption(key: String): SubtitleOption {
        val language = language?.takeIf { it.isNotBlank() && it != UNDETERMINED_LANGUAGE }.orEmpty()
        return SubtitleOption(
            url = key,
            language = language,
            label =
                label?.takeIf { it.isNotBlank() }
                    ?: language
                        .takeIf { it.isNotBlank() }
                        ?.let { StreamProcessor.localizedLanguageName(it) ?: it }
                        .orEmpty(),
            isAutoGenerated = false,
            origin = SubtitleOrigin.EMBEDDED,
            isForced = isForced,
        )
    }

    private sealed interface Pick {
        data object Off : Pick

        data class Track(
            val identity: String,
        ) : Pick
    }

    private companion object {
        const val EMBEDDED_PREFIX = "embedded:"
        const val UNDETERMINED_LANGUAGE = "und"

        fun keyOf(
            track: EmbeddedTextTrack,
            position: Int,
        ): String = "$EMBEDDED_PREFIX${track.id ?: "0.$position"}"
    }
}
