package io.github.aedev.flow.player.engine

/**
 * A playback failure in Media3's terms (`PlaybackException`, `ExoPlaybackException`), so upstream's error handling
 * ports as it is: the iOS player reports AVPlayer's and the bundled engine's failures with the error code Media3
 * would have given the same failure, and [type] and [rendererFormatSupport] as ExoPlaybackException has them.
 * The codes are Media3's numbers.
 */
open class PlaybackException(
    message: String?,
    cause: Throwable?,
    val errorCode: Int,
    val type: Int = TYPE_SOURCE,
    val rendererFormatSupport: Int = FORMAT_HANDLED,
) : Exception(message, cause) {
    val errorCodeName: String get() = getErrorCodeName(errorCode)

    companion object {
        const val TYPE_SOURCE = 0
        const val TYPE_RENDERER = 1
        const val TYPE_UNEXPECTED = 2
        const val TYPE_REMOTE = 3

        /** Media3's C.FORMAT_HANDLED and C.FORMAT_UNSUPPORTED_TYPE. */
        const val FORMAT_HANDLED = 4
        const val FORMAT_UNSUPPORTED_TYPE = 1

        const val ERROR_CODE_UNSPECIFIED = 1000
        const val ERROR_CODE_REMOTE_ERROR = 1001
        const val ERROR_CODE_BEHIND_LIVE_WINDOW = 1002
        const val ERROR_CODE_TIMEOUT = 1003
        const val ERROR_CODE_FAILED_RUNTIME_CHECK = 1004
        const val ERROR_CODE_IO_UNSPECIFIED = 2000
        const val ERROR_CODE_IO_NETWORK_CONNECTION_FAILED = 2001
        const val ERROR_CODE_IO_NETWORK_CONNECTION_TIMEOUT = 2002
        const val ERROR_CODE_IO_INVALID_HTTP_CONTENT_TYPE = 2003
        const val ERROR_CODE_IO_BAD_HTTP_STATUS = 2004
        const val ERROR_CODE_IO_FILE_NOT_FOUND = 2005
        const val ERROR_CODE_IO_NO_PERMISSION = 2006
        const val ERROR_CODE_IO_CLEARTEXT_NOT_PERMITTED = 2007
        const val ERROR_CODE_IO_READ_POSITION_OUT_OF_RANGE = 2008
        const val ERROR_CODE_PARSING_CONTAINER_MALFORMED = 3001
        const val ERROR_CODE_PARSING_MANIFEST_MALFORMED = 3002
        const val ERROR_CODE_PARSING_CONTAINER_UNSUPPORTED = 3003
        const val ERROR_CODE_PARSING_MANIFEST_UNSUPPORTED = 3004
        const val ERROR_CODE_DECODER_INIT_FAILED = 4001
        const val ERROR_CODE_DECODER_QUERY_FAILED = 4002
        const val ERROR_CODE_DECODING_FAILED = 4003
        const val ERROR_CODE_DECODING_FORMAT_EXCEEDS_CAPABILITIES = 4004
        const val ERROR_CODE_DECODING_FORMAT_UNSUPPORTED = 4005
        const val ERROR_CODE_AUDIO_TRACK_INIT_FAILED = 5001
        const val ERROR_CODE_AUDIO_TRACK_WRITE_FAILED = 5002
        const val ERROR_CODE_DRM_UNSPECIFIED = 6000
        const val ERROR_CODE_DRM_SCHEME_UNSUPPORTED = 6001
        const val ERROR_CODE_DRM_PROVISIONING_FAILED = 6002
        const val ERROR_CODE_DRM_CONTENT_ERROR = 6003
        const val ERROR_CODE_DRM_LICENSE_ACQUISITION_FAILED = 6004
        const val ERROR_CODE_DRM_DISALLOWED_OPERATION = 6005
        const val ERROR_CODE_DRM_SYSTEM_ERROR = 6006
        const val ERROR_CODE_DRM_DEVICE_REVOKED = 6007

        private val NAMES =
            mapOf(
                ERROR_CODE_UNSPECIFIED to "ERROR_CODE_UNSPECIFIED",
                ERROR_CODE_REMOTE_ERROR to "ERROR_CODE_REMOTE_ERROR",
                ERROR_CODE_BEHIND_LIVE_WINDOW to "ERROR_CODE_BEHIND_LIVE_WINDOW",
                ERROR_CODE_TIMEOUT to "ERROR_CODE_TIMEOUT",
                ERROR_CODE_FAILED_RUNTIME_CHECK to "ERROR_CODE_FAILED_RUNTIME_CHECK",
                ERROR_CODE_IO_UNSPECIFIED to "ERROR_CODE_IO_UNSPECIFIED",
                ERROR_CODE_IO_NETWORK_CONNECTION_FAILED to "ERROR_CODE_IO_NETWORK_CONNECTION_FAILED",
                ERROR_CODE_IO_NETWORK_CONNECTION_TIMEOUT to "ERROR_CODE_IO_NETWORK_CONNECTION_TIMEOUT",
                ERROR_CODE_IO_INVALID_HTTP_CONTENT_TYPE to "ERROR_CODE_IO_INVALID_HTTP_CONTENT_TYPE",
                ERROR_CODE_IO_BAD_HTTP_STATUS to "ERROR_CODE_IO_BAD_HTTP_STATUS",
                ERROR_CODE_IO_FILE_NOT_FOUND to "ERROR_CODE_IO_FILE_NOT_FOUND",
                ERROR_CODE_IO_NO_PERMISSION to "ERROR_CODE_IO_NO_PERMISSION",
                ERROR_CODE_IO_CLEARTEXT_NOT_PERMITTED to "ERROR_CODE_IO_CLEARTEXT_NOT_PERMITTED",
                ERROR_CODE_IO_READ_POSITION_OUT_OF_RANGE to "ERROR_CODE_IO_READ_POSITION_OUT_OF_RANGE",
                ERROR_CODE_PARSING_CONTAINER_MALFORMED to "ERROR_CODE_PARSING_CONTAINER_MALFORMED",
                ERROR_CODE_PARSING_MANIFEST_MALFORMED to "ERROR_CODE_PARSING_MANIFEST_MALFORMED",
                ERROR_CODE_PARSING_CONTAINER_UNSUPPORTED to "ERROR_CODE_PARSING_CONTAINER_UNSUPPORTED",
                ERROR_CODE_PARSING_MANIFEST_UNSUPPORTED to "ERROR_CODE_PARSING_MANIFEST_UNSUPPORTED",
                ERROR_CODE_DECODER_INIT_FAILED to "ERROR_CODE_DECODER_INIT_FAILED",
                ERROR_CODE_DECODER_QUERY_FAILED to "ERROR_CODE_DECODER_QUERY_FAILED",
                ERROR_CODE_DECODING_FAILED to "ERROR_CODE_DECODING_FAILED",
                ERROR_CODE_DECODING_FORMAT_EXCEEDS_CAPABILITIES to "ERROR_CODE_DECODING_FORMAT_EXCEEDS_CAPABILITIES",
                ERROR_CODE_DECODING_FORMAT_UNSUPPORTED to "ERROR_CODE_DECODING_FORMAT_UNSUPPORTED",
                ERROR_CODE_AUDIO_TRACK_INIT_FAILED to "ERROR_CODE_AUDIO_TRACK_INIT_FAILED",
                ERROR_CODE_AUDIO_TRACK_WRITE_FAILED to "ERROR_CODE_AUDIO_TRACK_WRITE_FAILED",
                ERROR_CODE_DRM_UNSPECIFIED to "ERROR_CODE_DRM_UNSPECIFIED",
                ERROR_CODE_DRM_SCHEME_UNSUPPORTED to "ERROR_CODE_DRM_SCHEME_UNSUPPORTED",
                ERROR_CODE_DRM_PROVISIONING_FAILED to "ERROR_CODE_DRM_PROVISIONING_FAILED",
                ERROR_CODE_DRM_CONTENT_ERROR to "ERROR_CODE_DRM_CONTENT_ERROR",
                ERROR_CODE_DRM_LICENSE_ACQUISITION_FAILED to "ERROR_CODE_DRM_LICENSE_ACQUISITION_FAILED",
                ERROR_CODE_DRM_DISALLOWED_OPERATION to "ERROR_CODE_DRM_DISALLOWED_OPERATION",
                ERROR_CODE_DRM_SYSTEM_ERROR to "ERROR_CODE_DRM_SYSTEM_ERROR",
                ERROR_CODE_DRM_DEVICE_REVOKED to "ERROR_CODE_DRM_DEVICE_REVOKED",
            )

        /** Media3's names, as its own `getErrorCodeName` gives them; unknown codes read "invalid error code". */
        fun getErrorCodeName(errorCode: Int): String = NAMES[errorCode] ?: "invalid error code"
    }
}
