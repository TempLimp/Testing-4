package io.github.aedev.flow.player.stream


/**
 * The text format of a caption track. [fmtQueryValue] is YouTube's timedtext `fmt` spelling, set
 * only for the formats that endpoint serves.
 */
enum class CaptionFormat(
    val mimeType: String,
    val fmtQueryValue: String? = null,
) {
    // Srv3SubtitleParser.MIME_TYPE (S10) and Media3's MimeTypes constants, spelled out.
    SRV3("application/x-youtube-srv3", "srv3"),
    VTT("text/vtt", "vtt"),
    SRT("application/x-subrip"),
    SSA("text/x-ssa"),
    TTML("application/ttml+xml"),
    ;

    companion object {
        /** The format a subtitle file's extension names, or null for one the player cannot read. */
        fun ofExtension(extension: String): CaptionFormat? =
            when (extension.lowercase()) {
                "srt" -> SRT
                "vtt" -> VTT
                "ass", "ssa" -> SSA
                "ttml", "dfxp" -> TTML
                else -> null
            }
    }
}

/** Where a caption track came from, which decides how it is labelled and whether it is kept. */
enum class CaptionSource {
    YOUTUBE,
    STORED,
    SIDECAR,
    PICKED,
}

/**
 * One caption track ready to fetch: a signed timedtext URL, a `file:` URI for a track stored beside
 * a download, or a `content:` URI for a subtitle file on the device.
 *
 * @param label the name a file gave the track, shown in place of the language name.
 */
data class ResolvedCaption(
    val languageTag: String,
    val isAutoGenerated: Boolean,
    val url: String,
    val format: CaptionFormat,
    val label: String? = null,
    val source: CaptionSource = CaptionSource.YOUTUBE,
) {
    val isTranslated: Boolean
        get() = url.contains("&${CaptionTrackResolver.TRANSLATED_PARAM}=")
}
