/**
 * Keeps a downloaded video's caption tracks on disk beside the download.
 *
 * Caption URLs are signed and expire within hours, so a download that only remembers the URL has
 * no captions the next time the app starts. The tracks themselves are a few KB of text, so they
 * are fetched once at download time and replayed from local files afterwards — which also makes
 * captions work with no network at all.
 */
class OfflineSubtitleStore
    constructor(
        // The shared client, read per request so a proxy change applies (upstream's live OkHttpClient).
        private val httpClient: () -> HttpClient,
    ) {
        private val rootDir: Path
            get() = Path(appFilesDir(), ROOT_DIR)

        private fun videoDir(videoId: String) = Path(rootDir, videoId.sanitized())

        /**
         * Resolve and store the video's native caption tracks. Auto-translations are skipped: they
         * are derived from a track we already keep and would multiply the stored files by twenty.
         *
         * @param known WebVTT tracks the caller already resolved, which spares a player request.
         */
        suspend fun saveForVideo(
            videoId: String,
            known: List<ResolvedCaption> = emptyList(),
        ): Int =
            withContext(Dispatchers.IO) {
                try {
                    val captions = known.filter { it.format == CaptionFormat.VTT }.ifEmpty { resolveCaptionTracks(videoId) }
                    if (captions.isEmpty()) {
                        Log.d(TAG, "No caption tracks to store for $videoId")
                        markResolvedWithoutTracks(videoId)
                        return@withContext 0
                    }
                    save(videoId, captions)
                } catch (e: CancellationException) {
                    throw e
                } catch (e: Exception) {
                    Log.w(TAG, "Storing captions for $videoId failed: ${e.message}")
                    0
                }
            }

        suspend fun save(
            videoId: String,
            captions: List<ResolvedCaption>,
        ): Int =
            withContext(Dispatchers.IO) {
                val dir = videoDir(videoId)
                if (runCatching { SystemFileSystem.createDirectories(dir) }.isFailure) {
                    Log.w(TAG, "Could not create caption dir for $videoId")
                    return@withContext 0
                }

                val stored = mutableListOf<JsonObject>()
                captions
                    .filterNot { it.isTranslated }
                    .forEach { caption ->
                        val fileName = captionFileName(caption.languageTag, caption.isAutoGenerated)
                        val target = Path(dir, fileName)
                        if (!downloadTo(caption.url, target)) return@forEach
                        stored +=
                            buildJsonObject {
                                put(KEY_LANGUAGE, caption.languageTag)
                                put(KEY_AUTO_GENERATED, caption.isAutoGenerated)
                                put(KEY_FILE, fileName)
                            }
                    }

                if (stored.isEmpty()) {
                    dir.deleteRecursively()
                    return@withContext 0
                }

                // The index keeps upstream's org.json shape: {"tracks":[{"language","autoGenerated","file"}]}.
                Path(dir, INDEX_FILE).writeText(JsonObject(mapOf(KEY_TRACKS to JsonArray(stored))).toString())
                Log.d(TAG, "Stored ${stored.size} offline caption track(s) for $videoId")
                stored.size
            }

        /** Whether captions were already looked up for [videoId], including a lookup that found none. */
        suspend fun isResolved(videoId: String): Boolean =
            withContext(Dispatchers.IO) { SystemFileSystem.metadataOrNull(Path(videoDir(videoId), INDEX_FILE))?.isRegularFile == true }

        private fun markResolvedWithoutTracks(videoId: String) {
            val dir = videoDir(videoId)
            if (runCatching { SystemFileSystem.createDirectories(dir) }.isFailure) return
            Path(dir, INDEX_FILE).writeText(JsonObject(mapOf(KEY_TRACKS to buildJsonArray { })).toString())
        }

        /** Caption tracks previously stored for [videoId], as file-backed captions. */
        suspend fun load(videoId: String): List<ResolvedCaption> =
            withContext(Dispatchers.IO) {
                val dir = videoDir(videoId)
                val index = Path(dir, INDEX_FILE)
                if (SystemFileSystem.metadataOrNull(index)?.isRegularFile != true) return@withContext emptyList()

                try {
                    val tracks =
                        (Json.parseToJsonElement(index.readText()) as? JsonObject)?.get(KEY_TRACKS) as? JsonArray
                            ?: return@withContext emptyList()
                    tracks.mapNotNull { element ->
                        val entry = element as? JsonObject ?: return@mapNotNull null
                        val file = Path(dir, entry.optString(KEY_FILE))
                        if (SystemFileSystem.metadataOrNull(file)?.isRegularFile != true) return@mapNotNull null
                        ResolvedCaption(
                            languageTag = entry.optString(KEY_LANGUAGE),
                            isAutoGenerated = (entry[KEY_AUTO_GENERATED] as? JsonPrimitive)?.booleanOrNull ?: false,
                            // java.io.File.toURI() of the stored file, which a player opens as a local URL.
                            url = "file://" + SystemFileSystem.resolve(file).toString().encodeURLPath(),
                            format = CaptionFormat.VTT,
                        )
                    }
                } catch (e: Exception) {
                    Log.w(TAG, "Reading offline captions for $videoId failed: ${e.message}")
                    emptyList()
                }
            }

        suspend fun delete(videoId: String) =
            withContext(Dispatchers.IO) {
                videoDir(videoId).deleteRecursively()
                Unit
            }

        /**
         * The video's caption tracks as fresh WebVTT URLs, with a machine translation into
         * [translateTo] when the video has no track in it. Caption URLs expire within hours, so
         * nothing that waited in a queue can use an old one.
         */
        suspend fun resolveOnline(
            videoId: String,
            translateTo: String? = null,
        ): List<ResolvedCaption> = withContext(Dispatchers.IO) { resolveCaptionTracks(videoId, translateTo) }

        /** The WebVTT body at [url], or null when the fetch fails or returns something else. */
        suspend fun fetchVtt(url: String): String? = withContext(Dispatchers.IO) { fetchVttBody(url) }

        private suspend fun resolveCaptionTracks(
            videoId: String,
            translateTo: String? = null,
        ): List<ResolvedCaption> {
            CAPTION_CLIENTS.forEach { client ->
                val response = YouTube.player(videoId, client = client).getOrNull()
                // VTT, not the default srv3: downloadTo() below validates and stores the raw
                // WEBVTT body as-is, and offline playback only ever builds VTT captions.
                val captions =
                    response
                        ?.let {
                            CaptionTrackResolver.resolve(
                                it,
                                format = CaptionFormat.VTT,
                                translateTo = translateTo,
                            )
                        }.orEmpty()
                if (captions.isNotEmpty()) return captions
            }
            return emptyList()
        }

        private suspend fun downloadTo(
            url: String,
            target: Path,
        ): Boolean {
            val body = fetchVttBody(url) ?: return false
            target.writeText(body)
            return true
        }

        private suspend fun fetchVttBody(url: String): String? =
            try {
                val response = httpClient().get(url)
                val body = response.bodyAsText()
                if (!response.status.isSuccess() || body.isBlank() || !body.startsWith(VTT_MAGIC)) {
                    Log.w(TAG, "Caption fetch rejected (${response.status.value})")
                    null
                } else {
                    body
                }
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                Log.w(TAG, "Caption fetch failed: ${e.message}")
                null
            }

        private fun captionFileName(
            languageTag: String,
            autoGenerated: Boolean,
        ): String = "${languageTag.sanitized()}${if (autoGenerated) ".auto" else ""}.vtt"

        private fun String.sanitized(): String = replace(Regex("[^A-Za-z0-9_.-]"), "_")

        // org.json's optString: the value as text, "" when absent.
        private fun JsonObject.optString(key: String): String = (this[key] as? JsonPrimitive)?.content.orEmpty()

        companion object {
            private const val TAG = "OfflineSubtitleStore"
            private const val ROOT_DIR = "offline_subtitles"
            private const val INDEX_FILE = "index.json"
            private const val KEY_TRACKS = "tracks"
            private const val KEY_LANGUAGE = "language"
            private const val KEY_AUTO_GENERATED = "autoGenerated"
            private const val KEY_FILE = "file"
            private const val VTT_MAGIC = "WEBVTT"

            private val CAPTION_CLIENTS = listOf(YouTubeClient.ANDROID_VR_NO_AUTH, YouTubeClient.MOBILE)
        }
    }
