#!/usr/bin/env python3
"""Converts upstream's generated Snowball stemmers (Java) to Kotlin for commonMain.

    python3 tools/snowball_to_kotlin.py           # writes shared/src/commonMain/kotlin/org/tartarus/snowball/ext/*.kt
    python3 tools/snowball_to_kotlin.py --check   # fails if the committed files differ from a fresh conversion

Upstream vendors the stemmers as Java generated by Snowball 3.1.1 (scripts/neuro/gen_snowball.sh), and Java does
not compile for iOS. The generated code is regular, so the conversion is line by line: a labelled block
(`lab0: { ... break lab0; }`) becomes `lab0@ do { ... break@lab0 } while (false)`, every loop and switch gets a
label so a bare `break;` or `continue;` keeps its Java target, a switch becomes `when`, and the Among and grouping
tables move into a companion object. The runtime (SnowballProgram, Among, SnowballStemmer) is ported by hand.
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "upstream", "app", "src", "main", "java", "org", "tartarus", "snowball", "ext")
TARGET = os.path.join(ROOT, "shared", "src", "commonMain", "kotlin", "org", "tartarus", "snowball", "ext")
LANGUAGES = ["english", "spanish", "portuguese", "french", "german", "italian", "russian"]

HEADER = """// Converted from upstream's {name}.java by tools/snowball_to_kotlin.py. Do not edit.
// Generated from {language}.sbl by Snowball 3.1.1 - https://snowballstem.org/ (BSD-3-Clause: iosApp/licenses/Snowball.txt)
@file:Suppress("ktlint", "FunctionName", "LocalVariableName", "PropertyName", "ClassName", "NAME_SHADOWING", "UNUSED_VARIABLE", "UNUSED_VALUE", "CanBeVal", "VARIABLE_WITH_REDUNDANT_INITIALIZER", "ASSIGNED_BUT_NEVER_ACCESSED_VARIABLE", "UNREACHABLE_CODE", "UNUSED_PARAMETER")

package org.tartarus.snowball.ext

import org.tartarus.snowball.Among
"""


def char_literal(code):
    return "'\\u%04x'" % int(code)


def convert(java, name, language):
    lines = java.split("\n")
    tables = []  # companion object lines
    body = []  # class body lines
    stack = []  # frames: (kind, label)
    counter = [0]
    pending = None  # (kind, label) waiting for its "{" on the next line
    in_case = []  # per switch frame: whether a case body is open
    i = 0
    n = len(lines)

    def fresh(prefix):
        counter[0] += 1
        return "%s%d" % (prefix, counter[0])

    def innermost(kinds):
        for kind, label in reversed(stack):
            if kind in kinds:
                return kind, label
        raise ValueError("no enclosing %s" % (kinds,))

    while i < n:
        raw = lines[i]
        line = raw.strip()
        indent = raw[: len(raw) - len(raw.lstrip())]
        i += 1

        if not line or line.startswith("//") or line.startswith("/*") or line.startswith("*") or line.startswith("@"):
            continue
        if line.startswith("package ") or line.startswith("import "):
            continue

        m = re.match(r"private final static Among\[\] (a_\d+) = \{$", line)
        if m:
            entries = []
            while True:
                entry = lines[i].strip()
                i += 1
                if entry == "};":
                    break
                em = re.match(r'new Among\(("(?:[^"\\]|\\.)*"), (-?\d+), (-?\d+)\),?$', entry)
                if not em:
                    raise ValueError("Among entry: %r" % entry)
                entries.append("            Among(%s, %s, %s)," % (em.group(1).replace("$", "\\$"), em.group(2), em.group(3)))
            tables.append("        private val %s =\n            arrayOf(\n%s\n            )\n" % (m.group(1), "\n".join("    " + e for e in entries)))
            continue

        m = re.match(r"private static final char\[\] (g_\w+) = \{([\d, ]+)\};$", line)
        if m:
            codes = [c.strip() for c in m.group(2).split(",") if c.strip()]
            tables.append("        private val %s = charArrayOf(%s)\n" % (m.group(1), ", ".join(char_literal(c) for c in codes)))
            continue

        m = re.match(r"public class (\w+) extends org\.tartarus\.snowball\.SnowballStemmer \{$", line)
        if m:
            body.append("class %s : org.tartarus.snowball.SnowballStemmer() {" % m.group(1))
            stack.append(("class", None))
            continue

        m = re.match(r"private (int|boolean) (\w+);$", line)
        if m and stack and stack[-1][0] == "class":
            kotlin_type, default = ("Int", "0") if m.group(1) == "int" else ("Boolean", "false")
            body.append("%sprivate var %s: %s = %s" % (indent, m.group(2), kotlin_type, default))
            continue

        m = re.match(r"private boolean (r_\w+)\(\) \{$", line)
        if m:
            body.append("%sprivate fun %s(): Boolean {" % (indent, m.group(1)))
            stack.append(("method", None))
            continue
        if line == "public boolean stem() {":
            body.append("%soverride fun stem(): Boolean {" % indent)
            stack.append(("method", None))
            continue
        if line == "public boolean equals( Object o ) {":
            ret = lines[i].strip()
            i += 1
            assert lines[i].strip() == "}", lines[i]
            i += 1
            cls = re.match(r"return o instanceof (\w+);$", ret).group(1)
            body.append("%soverride fun equals(other: Any?): Boolean = other is %s" % (indent, cls))
            continue
        if line == "public int hashCode() {":
            ret = lines[i].strip()
            i += 1
            assert lines[i].strip() == "}", lines[i]
            i += 1
            cls = re.match(r"return (\w+)\.class\.getName\(\)\.hashCode\(\);$", ret).group(1)
            body.append('%soverride fun hashCode(): Int = "org.tartarus.snowball.ext.%s".hashCode()' % (indent, cls))
            continue

        m = re.match(r"(lab\d+): \{$", line)
        if m:
            body.append("%s%s@ do {" % (indent, m.group(1)))
            stack.append(("block", m.group(1)))
            continue

        m = re.match(r"(?:(golab\d+): )?while \(true\)$", line)
        if m:
            label = m.group(1) or fresh("loop")
            assert lines[i].strip() == "{", lines[i]
            i += 1
            body.append("%s%s@ while (true) {" % (indent, label))
            stack.append(("loop", label))
            continue

        if line == "switch (among_var) {":
            label = fresh("sw")
            body.append("%s%s@ do {" % (indent, label))
            body.append("%s    when (among_var) {" % indent)
            stack.append(("switch", label))
            in_case.append(False)
            continue

        m = re.match(r"case (\d+):$", line)
        if m:
            assert stack[-1][0] == "switch"
            if in_case[-1]:
                body.append("%s    }" % indent)
            body.append("%s    %s -> {" % (indent, m.group(1)))
            in_case[-1] = True
            continue

        m = re.match(r"(if \(.*\)|else)$", line)
        if m:
            nxt = lines[i].strip()
            if nxt == "{":
                i += 1
                body.append("%s%s {" % (indent, m.group(1)))
                stack.append(("if", None))
                continue
            raise ValueError("if without braces: %r" % line)

        # A bare Java block scopes a local (`int c = ...`); in Kotlin a bare `{}` would be a lambda.
        if line == "{":
            body.append("%sdo {" % indent)
            stack.append(("plain", None))
            continue

        if line == "}" or line == "};":
            kind, label = stack.pop()
            if kind == "block" or kind == "plain":
                body.append("%s} while (false)" % indent)
            elif kind == "switch":
                if in_case.pop():
                    body.append("%s        }" % indent)
                body.append("%s    }" % indent)
                body.append("%s} while (false)" % indent)
            elif kind == "class":
                if tables:
                    body.append("")
                    body.append("    private companion object {")
                    body.extend(t.rstrip("\n") for t in tables)
                    body.append("    }")
                body.append("}")
            else:
                body.append("%s}" % indent)
            continue

        m = re.match(r"break (\w+);$", line)
        if m:
            body.append("%sbreak@%s" % (indent, m.group(1)))
            continue
        if line == "break;":
            kind, label = innermost(("loop", "switch"))
            body.append("%sbreak@%s" % (indent, label))
            continue
        if line == "continue;":
            kind, label = innermost(("loop",))
            body.append("%scontinue@%s" % (indent, label))
            continue

        m = re.match(r"int (\w+);$", line)
        if m:
            body.append("%svar %s: Int" % (indent, m.group(1)))
            continue
        m = re.match(r"int (\w+) = (.*);$", line)
        if m:
            body.append("%svar %s: Int = %s" % (indent, m.group(1), m.group(2)))
            continue

        if line.endswith(";"):
            statement = line[:-1]
            if re.search(r"\b(int|boolean|char|new|instanceof|String)\b", statement) and '"' not in statement:
                raise ValueError("unexpected Java statement: %r" % line)
            body.append("%s%s" % (indent, statement))
            continue

        raise ValueError("unhandled line %d: %r" % (i, line))

    assert not stack, stack
    out = HEADER.format(name=name, language=language) + "\n" + "\n".join(body) + "\n"
    # A Kotlin string template would read `$` in a slice literal; none of the stemmers have one, but keep it safe.
    return out


def main():
    check = "--check" in sys.argv[1:]
    failed = False
    for language in LANGUAGES:
        name = language + "Stemmer"
        with open(os.path.join(SOURCE, name + ".java"), encoding="utf-8") as f:
            kotlin = convert(f.read(), name, language)
        path = os.path.join(TARGET, name + ".kt")
        if check:
            try:
                with open(path, encoding="utf-8") as f:
                    current = f.read()
            except FileNotFoundError:
                current = None
            if current != kotlin:
                print("out of date: %s (run tools/snowball_to_kotlin.py)" % path)
                failed = True
        else:
            os.makedirs(TARGET, exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(kotlin)
            print("wrote %s" % path)
    if failed:
        sys.exit(1)
    if check:
        print("snowball_to_kotlin: %d stemmers up to date" % len(LANGUAGES))


if __name__ == "__main__":
    main()
